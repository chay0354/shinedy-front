// minPlan: המסלול המינימלי שבו הפריט זמין (לפי כללי 9.8):
// כסף/מצופה זהב + מויסנייט = SILVER · כסף/זהב + יהלומי מעבדה קטנים = DUO · זהב + יהלומים גדולים = GOLD
function minPlan(metal, stone, large) {
  const isLab = stone.includes('יהלו')
  if (isLab) return large ? 'gold' : 'combined'
  const isRealGold = metal.includes('זהב') && !metal.includes('מצופה')
  return isRealGold ? 'combined' : 'silver'
}

